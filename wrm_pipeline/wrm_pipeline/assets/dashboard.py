"""Dashboard evidence snapshot: dual-write the two dashboard datasets.

The asset materializes ``stations_latest`` and ``density_grid`` and writes
them to BOTH consumers:

- local ``dashboard/sources/wrm/wrm.duckdb`` (``SNAPSHOT_PATH``) — a
  gitignored, credential-free DuckDB file holding both tables; the Evidence
  source connection opens it READ_ONLY (``connection.yaml``).
- ``wrm/stations_latest.parquet`` and ``wrm/density_grid.parquet`` in the
  configured bucket (``config.BUCKET_NAME``), via DuckDB httpfs ``COPY ... TO``.

The local file is written first, so a clean checkout whose bucket is still
empty ends up with a usable snapshot even if the S3 upload later fails; it is
replaced atomically (sibling temp file + ``os.replace``) so READ_ONLY readers
only ever see the previous snapshot or the complete new one.

Credentials come exclusively from config/env names (``S3_*``/``HETZNER_*`` in
``config.py``) — nothing is hardcoded here, nothing is persisted into the
local file, and no credential value is ever logged.
"""

import os
import subprocess

import duckdb
from dagster import AssetExecutionContext, MaterializeResult, asset

# dashboard.py sits one directory below the package root (unlike the
# duckdb/ assets, which are two deep), so config is two dots up: this
# resolves both as wrm_pipeline.wrm_pipeline.config (tests) and
# wrm_pipeline.config (dagster CLI code-location loading).
from ..config import (
    BUCKET_NAME,
    HETZNER_ACCESS_KEY_ID,
    HETZNER_ENDPOINT,
    HETZNER_ENDPOINT_URL,
    HETZNER_SECRET_ACCESS_KEY,
    db_path,
)
from .duckdb.create_enhanced_views import create_duckdb_enhanced_views

# Repo root: two levels up from the wrm_pipeline/wrm_pipeline package dir
# (same derivation as config.db_path).
_REPO_ROOT = os.path.abspath(
    os.path.join(os.path.dirname(__file__), '..', '..', '..')
)
# Local snapshot consumed by the Evidence source connection (connection.yaml
# `options.filename`, opened READ_ONLY). The file is gitignored/untracked —
# it is a build artifact regenerated by every asset materialization.
SNAPSHOT_PATH = os.path.join(_REPO_ROOT, 'dashboard', 'sources', 'wrm', 'wrm.duckdb')

# S3 object keys (relative to BUCKET_NAME) for the two exported datasets.
STATIONS_EXPORT_KEY = 'wrm/stations_latest.parquet'
DENSITY_EXPORT_KEY = 'wrm/density_grid.parquet'

# Latest station records, projected to the dashboard's expected schema.
# Session-scoped TEMP tables: never persisted to db_path — they feed the two
# export targets (local snapshot + S3) below.
_STATIONS_SNAPSHOT_SQL = """
CREATE OR REPLACE TEMP TABLE stations_latest AS
SELECT station_id, name, bikes, spaces, total_docks, installed, lat, lon, timestamp
FROM wrm_stations_latest;
"""

# 1000m^2 grid cells: SQL port of bike_spatial_density_analysis._analyze_grid_density
# (~31.6m cell side, density_per_1000m2 == bikes per cell).
_DENSITY_SNAPSHOT_SQL = """
CREATE OR REPLACE TEMP TABLE density_grid AS
WITH bounds AS (
    SELECT MIN(lat) AS min_lat, MAX(lat) AS max_lat, MIN(lon) AS min_lon, MAX(lon) AS max_lon
    FROM wrm_stations_latest WHERE lat IS NOT NULL AND lon IS NOT NULL
),
grid AS (
    SELECT min_lat, min_lon,
           sqrt(1000) / 111320.0 AS lat_delta,
           sqrt(1000) / (111320.0 * cos(radians((min_lat + max_lat) / 2))) AS lon_delta
    FROM bounds
),
cells AS (
    SELECT floor((s.lat - g.min_lat) / g.lat_delta) AS i_lat,
           floor((s.lon - g.min_lon) / g.lon_delta) AS i_lon,
           s.bikes
    FROM wrm_stations_latest s, grid g
    WHERE s.lat IS NOT NULL AND s.lon IS NOT NULL
)
SELECT g.min_lat + (c.i_lat + 0.5) * g.lat_delta AS grid_lat,
       g.min_lon + (c.i_lon + 0.5) * g.lon_delta AS grid_lon,
       CAST(SUM(c.bikes) AS BIGINT) AS bike_count,
       CAST(COUNT(*) AS BIGINT) AS station_count,
       CAST(SUM(c.bikes) AS BIGINT) AS density_per_1000m2
FROM cells c, grid g
GROUP BY g.min_lat, g.min_lon, g.lat_delta, g.lon_delta, c.i_lat, c.i_lon;
"""

# Tables the local snapshot file must contain (Evidence's .sql sources do
# `FROM stations_latest` / `FROM density_grid` against it).
_SNAPSHOT_TABLES = ('stations_latest', 'density_grid')


def _quote_sql(value) -> str:
    """Inline a value into a single-quoted DuckDB literal (path/option safe)."""
    return str(value).replace("'", "''")


def _set_s3_option(conn, key: str, value) -> None:
    """Execute ``SET <key>='...';`` without letting the value reach the logs.

    DuckDB parser errors echo the offending statement, and for
    ``s3_access_key_id`` / ``s3_secret_access_key`` that statement embeds the
    credential itself. Any failure is therefore re-raised with only the option
    NAME (``from None`` drops the chained original for the same reason).
    """
    try:
        conn.execute(f"SET {key}='{_quote_sql(value)}';")
    except Exception:
        raise RuntimeError(
            f"DuckDB rejected SET {key}; value withheld from logs"
        ) from None


def _write_local_snapshot(conn) -> str:
    """Materialize both TEMP datasets into ``SNAPSHOT_PATH`` atomically.

    Writes into a sibling ``*.tmp`` file first, ``DETACH``es (which flushes
    and closes it), then ``os.replace``s it over ``SNAPSHOT_PATH``: READ_ONLY
    readers only ever observe the previous snapshot or the complete new one,
    never a half-written file. Credential-free by construction — only plain
    ``CREATE TABLE ... AS SELECT`` statements run here, and DuckDB keeps the
    session-scoped ``SET s3_*`` values out of every database file.

    Returns the absolute path that now holds the snapshot.
    """
    target = os.path.abspath(SNAPSHOT_PATH)
    os.makedirs(os.path.dirname(target), exist_ok=True)

    # Temp file + any leftover WAL: ours (this writer) or an orphan of a
    # crashed run that must not be replayed against the replacement file.
    tmp = target + '.tmp'
    for stale in (tmp, tmp + '.wal', target + '.wal'):
        if os.path.exists(stale):
            os.remove(stale)

    conn.execute(f"ATTACH '{_quote_sql(tmp)}' AS snapshot_db (READ_WRITE);")
    try:
        for table in _SNAPSHOT_TABLES:
            conn.execute(
                f"CREATE OR REPLACE TABLE snapshot_db.{table} AS "
                f"SELECT * FROM {table};"
            )
    except Exception:
        # Roll back to "no snapshot this run": never leave a partial temp
        # file — and never let that cleanup mask the original error (a stale
        # temp is cleared again at the top of the next run).
        try:
            conn.execute("DETACH snapshot_db;")
            if os.path.exists(tmp):
                os.remove(tmp)
        except Exception:
            pass
        raise
    conn.execute("DETACH snapshot_db;")

    os.replace(tmp, target)
    return target


@asset(
    name="evidence_data_snapshot",
    compute_kind="duckdb",
    group_name="dashboard",
    deps=[create_duckdb_enhanced_views],
)
def evidence_data_snapshot(context: AssetExecutionContext) -> MaterializeResult:
    """Write the analytics TEMP tables to the local snapshot and to S3.

    Local first (``wrm.duckdb``, atomic overwrite, no credentials involved),
    then the two ``s3://<BUCKET_NAME>/wrm/*.parquet`` objects via httpfs
    ``COPY TO``, so a broken upstream — or a failing bucket — never leaves a
    truncated local file behind. Credentials are read from config env names
    only and are never written to the log stream or the snapshot file.
    """
    if not BUCKET_NAME:
        raise ValueError(
            "BUCKET_NAME is not set; cannot determine the export bucket "
            "(set BUCKET_NAME in the environment / .env)"
        )

    stations_key = f"s3://{BUCKET_NAME}/{STATIONS_EXPORT_KEY}"
    density_key = f"s3://{BUCKET_NAME}/{DENSITY_EXPORT_KEY}"

    with duckdb.connect(db_path) as conn:
        # S3 SET pattern from query_station_summary.py so the S3-backed views
        # can be read; the endpoint must be a bare hostname for DuckDB. The
        # credential SETs go through _set_s3_option so a failure cannot echo
        # an access/secret key into Dagster's logs.
        conn.execute("INSTALL httpfs;")
        conn.execute("LOAD httpfs;")
        _set_s3_option(conn, "s3_region", "auto")
        _set_s3_option(conn, "s3_access_key_id", HETZNER_ACCESS_KEY_ID or "")
        _set_s3_option(
            conn, "s3_secret_access_key", HETZNER_SECRET_ACCESS_KEY or ""
        )
        endpoint = HETZNER_ENDPOINT_URL or HETZNER_ENDPOINT or ""
        if endpoint.startswith(('http://', 'https://')):
            endpoint = endpoint.replace('https://', '').replace('http://', '')
        _set_s3_option(conn, "s3_endpoint", endpoint)
        _set_s3_option(conn, "s3_use_ssl", "true")
        _set_s3_option(conn, "s3_url_style", "path")

        # Materialize + count first, so a broken upstream view fails before
        # anything is written anywhere (no partial local file, no S3 object).
        conn.execute(_STATIONS_SNAPSHOT_SQL)
        conn.execute(_DENSITY_SNAPSHOT_SQL)
        stations = conn.execute("SELECT COUNT(*) FROM stations_latest;").fetchone()[0]
        cells = conn.execute("SELECT COUNT(*) FROM density_grid;").fetchone()[0]

        # Local snapshot first: it needs no credentials, so a clean checkout
        # (bucket configured but still empty) still ends up with both tables
        # even if the uploads below fail.
        snapshot_path = _write_local_snapshot(conn)

        conn.execute(
            f"COPY stations_latest TO '{_quote_sql(stations_key)}' (FORMAT parquet);"
        )
        conn.execute(
            f"COPY density_grid TO '{_quote_sql(density_key)}' (FORMAT parquet);"
        )

    context.log.info(
        f"Exported dashboard snapshot to {stations_key} and {density_key} "
        f"and wrote local {snapshot_path} "
        f"({stations} stations, {cells} grid cells)"
    )
    return MaterializeResult(
        metadata={
            "bucket": BUCKET_NAME,
            "stations_latest_key": stations_key,
            "density_grid_key": density_key,
            "stations_latest_rows": stations,
            "density_grid_rows": cells,
            "local_snapshot_path": snapshot_path,
        }
    )


# --- evidence_build (B4.4) -------------------------------------------------
# Dashboard project dir and static build output, both env-overridable so a
# deployment can relocate the checkout; defaults derive from the repo root
# (same derivation as SNAPSHOT_PATH above).
DASHBOARD_DIR = os.environ.get('WRM_DASHBOARD_DIR') or os.path.join(_REPO_ROOT, 'dashboard')
# `evidence build` exports the static site into <dashboard>/build by default.
BUILD_DIR = os.environ.get('WRM_DASHBOARD_BUILD_DIR') or os.path.join(DASHBOARD_DIR, 'build')

# Secret env prefixes stripped from the npm child environment: the static
# build must be credential-free, so HETZNER_*/S3_* secrets are never handed
# to Node (and, as below, never logged).
_SECRET_ENV_PREFIXES = ('HETZNER_', 'S3_')


def _build_env() -> dict:
    """Environment for the npm child process, minus S3/Hetzner secrets.

    Reads os.environ only (no hardcoded keys); values are filtered out, never
    printed.
    """
    return {
        k: v
        for k, v in os.environ.items()
        if not k.upper().startswith(_SECRET_ENV_PREFIXES)
    }


@asset(
    name="evidence_build",
    compute_kind="npm",
    group_name="dashboard",
    deps=[evidence_data_snapshot],
)
def evidence_build(context: AssetExecutionContext) -> MaterializeResult:
    """Run ``npm run build`` (Evidence static export) over the snapshot.

    Depends on ``evidence_data_snapshot`` so the credential-free DuckDB file
    exists before the site is built; no S3 credentials reach the build.
    """
    if not os.path.isfile(os.path.join(DASHBOARD_DIR, 'package.json')):
        raise FileNotFoundError(
            f"dashboard package.json not found under {DASHBOARD_DIR} "
            "(set WRM_DASHBOARD_DIR to relocate it)"
        )
    if not os.path.isdir(os.path.join(DASHBOARD_DIR, 'node_modules')):
        raise FileNotFoundError(
            f"node_modules missing in {DASHBOARD_DIR}; run `npm ci` there first"
        )

    try:
        proc = subprocess.run(
            ['npm', 'run', 'build'],
            cwd=DASHBOARD_DIR,
            env=_build_env(),
            capture_output=True,
            text=True,
        )
    except FileNotFoundError as exc:
        raise FileNotFoundError("npm not found on PATH") from exc

    # Log command output tails only; the environment (and any secrets in it)
    # is never logged.
    if proc.stdout:
        context.log.info(proc.stdout[-2000:])
    if proc.returncode != 0:
        context.log.error(proc.stderr[-2000:])
        raise RuntimeError(f"`npm run build` failed with exit code {proc.returncode}")

    return MaterializeResult(
        metadata={
            "dashboard_dir": DASHBOARD_DIR,
            "build_dir": BUILD_DIR,
            "build_exists": os.path.isdir(BUILD_DIR),
            "command": "npm run build",
        }
    )


# --- evidence_deploy (B5.3) ------------------------------------------------
# Static-hosting handoff: no upload happens here (the GitHub Pages workflow
# owns the publish step), so this asset only validates the credential-free
# build output produced by ``evidence_build``.


@asset(
    name="evidence_deploy",
    compute_kind="static",
    group_name="dashboard",
    deps=[evidence_build],
)
def evidence_deploy(context: AssetExecutionContext) -> MaterializeResult:
    """Verify the static build output is ready for static hosting.

    Depends on ``evidence_build``; checks that ``BUILD_DIR`` exists and
    counts its files so the materialization records what would be published.
    No S3 upload occurs here (the Pages workflow handles upload), and the
    environment is filtered through ``_build_env`` so secrets never reach
    any child process or the logs.
    """
    if not os.path.isdir(BUILD_DIR):
        raise FileNotFoundError(
            f"static build output not found at {BUILD_DIR} "
            "(set WRM_DASHBOARD_BUILD_DIR to relocate it)"
        )

    file_count = sum(
        len(filenames)
        for _, _, filenames in os.walk(BUILD_DIR)
    )
    if file_count == 0:
        raise RuntimeError(f"static build output at {BUILD_DIR} is empty")

    # Ensure the deploy context inherits the same secret-free environment
    # contract as the build (currently upload-free, but kept consistent so a
    # future uploader cannot accidentally receive HETZNER_*/S3_* credentials).
    env = _build_env()
    assert all(not k.upper().startswith(_SECRET_ENV_PREFIXES) for k in env)

    context.log.info(
        f"Static build ready at {BUILD_DIR} ({file_count} files); "
        "upload handled by the Pages workflow"
    )
    return MaterializeResult(
        metadata={
            "build_dir": BUILD_DIR,
            "file_count": file_count,
            "upload": "pages-workflow",
        }
    )
